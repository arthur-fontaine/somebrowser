import Foundation

/// Emits every file that would otherwise be a hand-maintained central list:
/// `Package.swift`, `Generated/Branding/Branding.swift`, `Generated/App/*.swift`.
enum Generator {
    static let header = "// GENERATED by forkctl — do not edit. Change feature.json / Fork/fork.json and run `./forkctl generate`.\n"

    static func run(_ p: Project) throws {
        try write(packageSwift(p), to: p.path("Package.swift"))
        try write(branding(p), to: p.path("Generated/Branding/Branding.swift"))
        try write(registry(p), to: p.path("Generated/App/FeatureRegistry.swift"))
        try write(mainSwift(p), to: p.path("Generated/App/main.swift"))
    }

    static func write(_ contents: String, to url: URL) throws {
        try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
        if let existing = FileManager.default.contents(atPath: url.path), String(decoding: existing, as: UTF8.self) == contents {
            return  // keep mtimes stable so incremental builds stay incremental
        }
        try contents.write(to: url, atomically: true, encoding: .utf8)
    }

    // MARK: Package.swift

    static func packageSwift(_ p: Project) -> String {
        var targets: [String] = []
        let mainActor = "swiftSettings: mainActor"
        targets.append(#".target(name: "BrowserBranding", path: "Generated/Branding")"#)
        targets.append(#".target(name: "BrowserCore", dependencies: ["BrowserBranding"], path: "Core/Sources", \#(mainActor))"#)
        targets.append(#".target(name: "BrowserTesting", dependencies: ["BrowserCore"], path: "Testing/Sources", \#(mainActor))"#)
        targets.append(#".testTarget(name: "BrowserCoreTests", dependencies: ["BrowserCore", "BrowserTesting"], path: "Core/Tests", \#(mainActor))"#)
        targets.append(#".target(name: "BrowserShell", dependencies: ["BrowserCore"], path: "Shell/Sources", \#(mainActor))"#)
        if exists(p, "Shell/Tests") {
            targets.append(#".testTarget(name: "BrowserShellTests", dependencies: ["BrowserShell", "BrowserTesting"], path: "Shell/Tests", \#(mainActor))"#)
        }

        let engineDir = engineDirectory(p)
        for t in p.engine.targets {
            targets.append(engineTarget(t, p: p))
        }
        if let dir = engineDir, exists(p, "\(dir)/Tests") {
            targets.append(".testTarget(name: \"\(p.engine.module)Tests\", dependencies: [\"\(p.engine.module)\", \"BrowserTesting\"], path: \"\(dir)/Tests\", \(mainActor))")
        }

        var appDeps = ["\"BrowserCore\"", "\"BrowserShell\"", "\"\(p.engine.module)\""]
        for f in p.enabled {
            var modules = f.manifest.modules
            var linkerSettings = f.manifest.frameworks.map { ".linkedFramework(\"\($0)\")" }
            if let crate = f.manifest.cargo {
                let dir = "\(f.directory)/\(crate)"
                targets.append(".systemLibrary(name: \"\(f.targetName)Native\", path: \"\(dir)/include\")")
                modules.append("\(f.targetName)Native")
                linkerSettings.append(".unsafeFlags([\"-L\", \"\(p.root.appendingPathComponent(dir).path)/target/release\"])")
            }
            let deps = (["BrowserCore"] + modules).map { "\"\($0)\"" }.joined(separator: ", ")
            let linker = linkerSettings.isEmpty ? "" : ", linkerSettings: [" + linkerSettings.joined(separator: ", ") + "]"
            let resources = exists(p, "\(f.directory)/Resources") ? ", resources: [.copy(\"../Resources\")]" : ""
            targets.append(".target(name: \"\(f.targetName)\", dependencies: [\(deps)], path: \"\(f.directory)/Sources\"\(resources), \(mainActor)\(linker))")
            if exists(p, "\(f.directory)/Tests") {
                targets.append(".testTarget(name: \"\(f.testTargetName)\", dependencies: [\"\(f.targetName)\", \"BrowserCore\", \"BrowserTesting\"], path: \"\(f.directory)/Tests\", \(mainActor))")
            }
            appDeps.append("\"\(f.targetName)\"")
        }
        if exists(p, "Tests/E2E") {
            targets.append(".testTarget(name: \"BrowserE2ETests\", dependencies: [\"BrowserTesting\"], path: \"Tests/E2E\")")
        }
        targets.append(".executableTarget(name: \"BrowserApp\", dependencies: [\(appDeps.joined(separator: ", "))], path: \"Generated/App\", \(mainActor))")

        return """
        // swift-tools-version: 6.2
        \(header)
        import PackageDescription

        let mainActor: [SwiftSetting] = [.defaultIsolation(MainActor.self)]

        let package = Package(
            name: "\(p.brand.executableName)",
            platforms: [.macOS("26.0")],
            products: [.executable(name: "\(p.brand.executableName)", targets: ["BrowserApp"])],
            targets: [
                \(targets.joined(separator: ",\n        "))
            ]
        )

        """
    }

    static func engineDirectory(_ p: Project) -> String? {
        p.engine.targets.first(where: { $0.name == p.engine.module }).map { ($0.path as NSString).deletingLastPathComponent }
    }

    static func engineTarget(_ t: EngineManifest.Target, p: Project) -> String {
        let deps = (t.dependencies ?? []).map { "\"\($0)\"" }.joined(separator: ", ")
        let vendor = p.path("Vendor").path
        func subst(_ s: String) -> String { s.replacingOccurrences(of: "$(VENDOR)", with: vendor) }
        var settings: [String] = []
        if t.language == "swift" {
            settings.append("swiftSettings: mainActor")
        } else {
            let cflags = (t.unsafeCFlags ?? []).map { "\"\(subst($0))\"" }
            if !cflags.isEmpty {
                settings.append("cSettings: [.unsafeFlags([\(cflags.joined(separator: ", "))])]")
                settings.append("cxxSettings: [.unsafeFlags([\(cflags.joined(separator: ", "))])]")
            }
        }
        var linker: [String] = (t.frameworks ?? []).map { ".linkedFramework(\"\($0)\")" }
        let lflags = (t.unsafeLinkerFlags ?? []).map { "\"\(subst($0))\"" }
        if !lflags.isEmpty { linker.append(".unsafeFlags([\(lflags.joined(separator: ", "))])") }
        if !linker.isEmpty { settings.append("linkerSettings: [\(linker.joined(separator: ", "))]") }
        let kind = t.type == "executable" ? "executableTarget" : "target"
        let extra = settings.isEmpty ? "" : ", " + settings.joined(separator: ", ")
        return ".\(kind)(name: \"\(t.name)\", dependencies: [\(deps)], path: \"\(t.path)\"\(extra))"
    }

    static func exists(_ p: Project, _ relative: String) -> Bool {
        FileManager.default.fileExists(atPath: p.path(relative).path)
    }

    // MARK: Branding

    static func branding(_ p: Project) -> String {
        let b = p.brand
        return """
        \(header)
        /// Product identity. Change it with `./forkctl rename` (writes `Fork/fork.json`), never by editing literals.
        public enum Brand {
            public static let name = \(swiftStringLiteral(b.name))
            public static let executableName = \(swiftStringLiteral(b.executableName))
            public static let bundleIdentifier = \(swiftStringLiteral(b.bundleId))
            public static let urlScheme = \(swiftStringLiteral(b.urlScheme))
            public static let userAgentBrand = \(swiftStringLiteral(b.userAgentBrand))
            public static let homepage = \(swiftStringLiteral(b.homepage))
            public static let repository = \(swiftStringLiteral(b.repository))
            public static let copyright = \(swiftStringLiteral(b.copyright))
            public static let engineID = \(swiftStringLiteral(p.engine.id))
            public static let engineName = \(swiftStringLiteral(p.engine.name))
        }

        """
    }

    // MARK: Registry

    static func registry(_ p: Project) -> String {
        var imports = Set<String>(["BrowserCore"])
        var entries: [String] = []
        for f in p.enabled {
            imports.insert(f.targetName)
            entries.append(registration(f, p: p))
        }
        let settingOverrides = p.settingOverrides.sorted { $0.key < $1.key }
            .map { "\(swiftStringLiteral($0.key)): \($0.value.swiftSettingValue)" }
        let options = p.engineOptions.sorted { $0.key < $1.key }
            .map { "\(swiftStringLiteral($0.key)): \($0.value.swiftSettingValue)" }
        return """
        \(header)
        \(imports.sorted().map { "import \($0)" }.joined(separator: "\n"))

        enum FeatureRegistry {
            /// Enabled features in activation order (capability providers first).
            static let all: [FeatureRegistration] = [
                \(entries.joined(separator: ",\n        "))
            ]

            /// Setting default overrides from Defaults/fork.json and Fork/fork.json.
            static let settingOverrides: [String: SettingValue] = [\(settingOverrides.isEmpty ? ":" : settingOverrides.joined(separator: ", "))]

            /// Engine options from Defaults/fork.json and Fork/fork.json.
            static let engineOptions: [String: SettingValue] = [\(options.isEmpty ? ":" : options.joined(separator: ", "))]
        }

        """
    }

    static func registration(_ f: FeatureEntry, p: Project) -> String {
        let m = f.manifest
        let commands = m.commands.map { c -> String in
            let shortcut: String? = {
                if let o = p.shortcutOverrides[c.id] { return o.isEmpty ? nil : o }
                return c.shortcut
            }()
            return "CommandDescriptor(id: \(swiftStringLiteral(c.id)), title: \(swiftStringLiteral(c.title)), "
                + "shortcut: \(shortcut.map(swiftStringLiteral) ?? "nil"), "
                + "alternateShortcuts: [\((c.alternateShortcuts ?? []).map(swiftStringLiteral).joined(separator: ", "))], "
                + "menu: \(c.menu.map(swiftStringLiteral) ?? "nil"), group: \(c.group.map(swiftStringLiteral) ?? "nil"), "
                + "order: \(c.order ?? 1000), palette: \(c.palette ?? true), "
                + "keywords: [\((c.keywords ?? []).map(swiftStringLiteral).joined(separator: ", "))])"
        }
        let settings = m.settings.map { s -> String in
            let value = p.settingOverrides[s.key] ?? s.default
            return "SettingDescriptor(key: \(swiftStringLiteral(s.key)), title: \(swiftStringLiteral(s.title)), "
                + "kind: .\(s.type), defaultValue: \(value.swiftSettingValue), "
                + "description: \(s.description.map(swiftStringLiteral) ?? "nil"), "
                + "options: [\((s.options ?? []).map(swiftStringLiteral).joined(separator: ", "))], "
                + "section: \(s.section.map(swiftStringLiteral) ?? "nil"))"
        }
        func list(_ xs: [String]) -> String { "[" + xs.map(swiftStringLiteral).joined(separator: ", ") + "]" }
        return """
        FeatureRegistration(
                    manifest: FeatureManifest(
                        id: \(swiftStringLiteral(m.id)), name: \(swiftStringLiteral(m.name)), summary: \(swiftStringLiteral(m.summary)),
                        provides: \(list(m.provides)), requires: \(list(m.requires)), optional: \(list(m.optional)),
                        commands: [\(commands.joined(separator: ",\n                    "))],
                        settings: [\(settings.joined(separator: ",\n                    "))]
                    ),
                    make: { \(m.entry)(context: $0) }
                )
        """
    }

    // MARK: main.swift

    static func mainSwift(_ p: Project) -> String {
        """
        \(header)
        import BrowserCore
        import BrowserShell
        import \(p.engine.module)

        ShellApplication.main(
            engine: \(p.engine.entry).self,
            features: FeatureRegistry.all,
            settingOverrides: FeatureRegistry.settingOverrides,
            engineOptions: FeatureRegistry.engineOptions
        )

        """
    }
}
